function systemLocale(): string {
	const intlLocale = Intl.DateTimeFormat().resolvedOptions().locale;
	if (intlLocale) return intlLocale;
	return process.env.LC_ALL ?? process.env.LC_MESSAGES ?? process.env.LANG ?? "en";
}

export function detectUiLanguage(setting: LanguageSetting, locale = systemLocale()): UiLanguage {
	if (setting !== "auto") return setting;
	return locale.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

let activeSetting: LanguageSetting = "auto";
let activeLanguage: UiLanguage = "en";

export function setLanguageSetting(setting: LanguageSetting, locale?: string): void {
	activeSetting = setting;
	activeLanguage = detectUiLanguage(setting, locale);
}

export function getLanguageSetting(): LanguageSetting {
	return activeSetting;
}

export function getUiLanguage(): UiLanguage {
	return activeLanguage;
}

export function t(key: MessageKey, values: Readonly<Record<string, string | number>> = {}): string {
	const messages = activeLanguage === "zh-CN" ? ZH_CN_MESSAGES : EN_MESSAGES;
	const template = messages[key] ?? EN_MESSAGES[key];
	return template.replace(/\{([^}]+)\}/g, (placeholder, name: string) => {
		const value = values[name];
		return value === undefined ? placeholder : String(value);
	});
}
